package Clases;

public abstract class Materiales {
	private String Titulo;
	private String Autor;
	private String Anio;
	
	private String setTitulo() {
		return Titulo;
	}
	private String setAutor() {
		return Autor;
	}
	private String setAnio() {
		return Anio;
	}
	private String getTitulo() {
		return Titulo;
	}
	private String getAutor() {
		return Autor;
	}
	private String getAnio() {
		return Anio;
	}
}
